"""Check that every `path:line` citation in the model's answer is real.

A citation is valid when the file exists in the repo, the line range is
inside the file, and the agent was shown those lines during this run.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

CITATION = re.compile(r"`([A-Za-z0-9_./\-]+\.[A-Za-z0-9_]+|[A-Za-z0-9_./\-]*(?:Makefile|Dockerfile|Procfile))(?::(\d+)(?:-(\d+))?)?`")


@dataclass
class CitationReport:
    valid: list[str] = field(default_factory=list)
    unread: list[str] = field(default_factory=list)       # real code the agent was never shown
    bad_lines: list[str] = field(default_factory=list)    # line numbers out of range
    missing: list[str] = field(default_factory=list)      # file does not exist

    @property
    def total(self) -> int:
        return len(self.valid) + len(self.unread) + len(self.bad_lines) + len(self.missing)

    @property
    def problems(self) -> list[str]:
        return self.missing + self.bad_lines


def _covered(ranges: list[tuple[int, int]], lo: int, hi: int) -> bool:
    return all(any(a <= n <= b for a, b in ranges) for n in range(lo, hi + 1))


def check_citations(markdown: str, root: str | Path, files_read: dict[str, int],
                    ranges_read: dict[str, list[tuple[int, int]]] | None = None) -> CitationReport:
    root = Path(root).resolve()
    report = CitationReport()
    seen = set()
    for match in CITATION.finditer(markdown):
        rel, start, end = match.group(1), match.group(2), match.group(3)
        if start is None and "/" not in rel and not (root / rel).is_file():
            # bare names like `config.yaml` that are not real files are prose, not citations
            continue
        if rel.startswith("/"):
            if not (root / rel.lstrip("/")).is_file():
                continue  # a path on the reader's machine, like `/etc/ssl/cert.pem`, not a repo citation
            rel = rel.lstrip("/")
        token = match.group(0).strip("`")
        if token in seen:
            continue
        seen.add(token)
        while rel.startswith("./"):
            rel = rel[2:]
        path = (root / rel).resolve()
        if root not in path.parents or not path.is_file():
            report.missing.append(token)
            continue
        lo = hi = None
        if start is not None:
            try:
                total = files_read.get(rel)
                if total is None:
                    total = len(path.read_text(errors="ignore").splitlines())
            except OSError:
                report.missing.append(token)
                continue
            lo, hi = int(start), int(end or start)
            if lo < 1 or hi < lo or hi > total:
                report.bad_lines.append(token)
                continue
        seen_lines = lo is None or ranges_read is None or _covered(ranges_read.get(rel, []), lo, hi)
        if rel in files_read and seen_lines:
            report.valid.append(token)
        else:
            report.unread.append(token)
    return report


def render_footer(report: CitationReport, steps: int, model: str) -> str:
    lines = [
        "",
        "---",
        "",
        f"<sub>Generated by [Marg](https://github.com/mqhnish/marg) on the BharatCode API ({model}) "
        f"in {steps} agent steps. Citations checked: {len(report.valid)} verified against files the agent read"
        + (f", {len(report.unread)} point to real code the agent did not read" if report.unread else "")
        + (f", {len(report.problems)} could not be verified (listed below)" if report.problems else "")
        + ".</sub>",
    ]
    if report.problems:
        lines.append("")
        lines.append("<sub>Unverified citations: " + ", ".join(f"`{p}`" for p in report.problems) + "</sub>")
    return "\n".join(lines) + "\n"
